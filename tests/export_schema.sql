-- Exports the live public schema (tables, constraints, indexes, views, functions, triggers,
-- RLS policies, grants) as ordered DDL rows, so a local replica can be rebuilt for testing.
-- Read-only. Run in the Supabase SQL editor, then download the result as CSV.
with
tbl as (
  select c.oid, c.relname from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind in ('r','p')
),
parts as (
  -- 1. extensions
  select 10 as ord, e.extname as k, format('create extension if not exists %I;', e.extname) as ddl
  from pg_extension e where e.extname not in ('plpgsql')
  union all
  -- 2. enum types
  select 20, t.typname, format('create type public.%I as enum (%s);', t.typname,
         (select string_agg(quote_literal(enumlabel), ', ' order by enumsortorder) from pg_enum where enumtypid = t.oid))
  from pg_type t join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public' and t.typtype = 'e'
  union all
  -- 3. tables with columns
  select 30, t.relname, format('create table public.%I (%s);', t.relname, (
    select string_agg(format('%I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
             case when a.attidentity = 'a' then ' generated always as identity'
                  when a.attidentity = 'd' then ' generated by default as identity' else '' end,
             case when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(d.adbin, d.adrelid) || ') stored'
                  when d.adbin is not null and a.attidentity = '' then ' default ' || pg_get_expr(d.adbin, d.adrelid) else '' end,
             case when a.attnotnull then ' not null' else '' end), ', ' order by a.attnum)
    from pg_attribute a left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
    where a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped))
  from tbl t
  union all
  -- 4. primary key / unique / check constraints
  select 40, t.relname || '.' || co.conname, format('alter table public.%I add constraint %I %s;', t.relname, co.conname, pg_get_constraintdef(co.oid))
  from pg_constraint co join tbl t on t.oid = co.conrelid where co.contype in ('p','u','c','x')
  union all
  -- 5. foreign keys (after all tables exist)
  select 50, t.relname || '.' || co.conname, format('alter table public.%I add constraint %I %s;', t.relname, co.conname, pg_get_constraintdef(co.oid))
  from pg_constraint co join tbl t on t.oid = co.conrelid where co.contype = 'f'
  union all
  -- 6. indexes that are not backing a constraint
  select 60, i.indexname, i.indexdef || ';'
  from pg_indexes i where i.schemaname = 'public'
    and not exists (select 1 from pg_constraint co where co.conname = i.indexname)
  union all
  -- 7. views
  select 70, v.viewname, format('create or replace view public.%I as %s', v.viewname, pg_get_viewdef(format('public.%I', v.viewname)::regclass, true))
  from pg_views v where v.schemaname = 'public'
  union all
  -- 8. functions (skip extension-owned)
  select 80, p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')', pg_get_functiondef(p.oid) || ';'
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind in ('f','p')
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
  union all
  -- 9. triggers on public tables and on auth.users (e.g. new-user -> profile)
  select 90, c.relname || '.' || tg.tgname, pg_get_triggerdef(tg.oid) || ';'
  from pg_trigger tg join pg_class c on c.oid = tg.tgrelid join pg_namespace n on n.oid = c.relnamespace
  where not tg.tgisinternal and (n.nspname = 'public' or (n.nspname = 'auth' and c.relname = 'users'))
  union all
  -- 10. row level security switches
  select 100, t.relname, format('alter table public.%I enable row level security;', t.relname)
  from pg_class t join pg_namespace n on n.oid = t.relnamespace where n.nspname = 'public' and t.relrowsecurity
  union all
  -- 11. policies
  select 110, p.tablename || '.' || p.policyname,
    format('create policy %I on public.%I as %s for %s to %s%s%s;', p.policyname, p.tablename, p.permissive, p.cmd,
      array_to_string(p.roles, ', '),
      coalesce(' using (' || p.qual || ')', ''), coalesce(' with check (' || p.with_check || ')', ''))
  from pg_policies p where p.schemaname = 'public'
  union all
  -- 12. table grants to API roles
  select 120, g.table_name || '.' || g.grantee || '.' || g.privilege_type,
    format('grant %s on public.%I to %I;', g.privilege_type, g.table_name, g.grantee)
  from information_schema.role_table_grants g
  where g.table_schema = 'public' and g.grantee in ('anon','authenticated','service_role')
  union all
  -- 13. column-level grants (only where the table itself isn't granted)
  select 130, cp.table_name || '.' || cp.column_name || '.' || cp.grantee || '.' || cp.privilege_type,
    format('grant %s (%I) on public.%I to %I;', cp.privilege_type, cp.column_name, cp.table_name, cp.grantee)
  from information_schema.column_privileges cp
  where cp.table_schema = 'public' and cp.grantee in ('anon','authenticated')
    and not exists (select 1 from information_schema.role_table_grants g where g.table_schema = 'public'
                    and g.table_name = cp.table_name and g.grantee = cp.grantee and g.privilege_type = cp.privilege_type)
  union all
  -- 14. function execute grants / revokes
  select 140, p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')',
    format('revoke all on function public.%I(%s) from public, anon, authenticated;', p.proname, pg_get_function_identity_arguments(p.oid))
    || coalesce((select string_agg(format(' grant execute on function public.%I(%s) to %s;', p.proname, pg_get_function_identity_arguments(p.oid),
                   case when a.grantee = 0 then 'public' else quote_ident(pg_get_userbyid(a.grantee)) end), '')
                 from aclexplode(p.proacl) a
                 where a.privilege_type = 'EXECUTE' and (a.grantee = 0 or pg_get_userbyid(a.grantee) in ('anon','authenticated','service_role'))),
                ' grant execute on function public.' || quote_ident(p.proname) || '(' || pg_get_function_identity_arguments(p.oid) || ') to public;')
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind in ('f','p')
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
)
select ord, k, ddl from parts order by ord, k;
